/* Exact inclusion-minimal crossings with at most one arm per declared group.
 * Increasing cardinality makes every proper crossing subset available before a
 * superset. Such a superset cannot be minimal, even if its band is nonmonotonic.
 * No economic monotonicity or numerical dominance is assumed. */
"use strict";
function minimalCrossings(groups, bandOf, crosses) {
  const ids=groups.flat(), seen=new Set(ids);
  if(seen.size!==ids.length||groups.some(g=>!g.length))throw Error("[BLOCKED] minimal search groups must be nonempty and disjoint");
  const cuts=[],trie={children:new Map()},counts={evaluated:0,pruned_prefixes:0,eligible_nonempty_sets:groups.reduce((n,g)=>n*BigInt(g.length+1),1n)-1n};
  // The trie follows group order, as does generation. Query only paths whose
  // arms occur in this prefix; do not scan thousands of unrelated cuts.
  function containsCut(selected,k,node=trie,at=0,depth=0) {
    if(node.terminal&&depth<k)return true;
    for(let i=at;i<selected.length;i++) {
      const next=node.children.get(selected[i]);
      if(next&&containsCut(selected,k,next,i+1,depth+1))return true;
    }
    return false;
  }
  function remember(set) {
    let node=trie;
    for(const id of set){if(!node.children.has(id))node.children.set(id,{children:new Map()});node=node.children.get(id);}
    node.terminal=true;
  }
  function* sets(at,remaining,selected,k) {
    if(containsCut(selected,k)){counts.pruned_prefixes++;return;}
    if(remaining===0){yield selected.slice();return;}
    if(groups.length-at<remaining)return;
    for(let i=at;i<=groups.length-remaining;i++)for(const id of groups[i]) {
      selected.push(id);yield*sets(i+1,remaining-1,selected,k);selected.pop();
    }
  }
  for(let k=1;k<=groups.length;k++)for(const set of sets(0,k,[],k)) {
    const b=bandOf(set);counts.evaluated++;
    if(!Array.isArray(b)||b.length!==2||!b.every(Number.isFinite))throw Error("[BLOCKED] minimal search band must be finite pair");
    if(crosses(b)){cuts.push({set,b});remember(set);}
  }
  return {cuts,counts:{...counts,eligible_nonempty_sets:String(counts.eligible_nonempty_sets),minimal_crossings:cuts.length},
    proof:"All nonempty eligible sets are generated by cardinality, with at most one per disjoint source group. A pruned prefix contains a proper crossing subset, so every completion is nonminimal regardless of engine monotonicity."};
}
module.exports={minimalCrossings};
