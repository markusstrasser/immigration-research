#!/usr/bin/env python3
"""Each group's 2024 line amounts on the sept29 case, for the debt legacy of the comparators.

The white replacement lane's sept29 re-key (`white_replacement_2026_09_28/rekey_sept29.py`, imported read-only; its
module-level build reads files and writes nothing) prices every line of the adopted case for any population on one
code path: the case's nationals, responses and capital; each group's rough CPS/MEPS keys on audit row 4's weights,
every slice scaled to the 39,712,493 people the account prices. This script runs its `setup()` (its own gates:
the dumps are the adopted bands, the row-4 frame, the positive controls) and `run29()` for four groups, on both
bases (cash: the cash set; accrual: the case's pension rule at each group's own accrual per tax dollar) and at both
end specifications (48 / 11), and writes every line's amount and response:

  mexican_origin_engine   the engine's own union amounts (the debt lane's anchor; parity input)
  mexican_origin_rough    the union on the rough keys every comparator uses (the like-for-like reference)
  A1_third_plus_nh_white  third-plus-generation non-Hispanic whites at their own ages
  all_residents_slice     an average-resident slice

Gate: each group's cost from the written amounts equals rekey_summary_sept29.csv's cost (5e-5, its 4 decimals).
Output: derived/group_lines_sept29.csv (tracked). Run from the repository root:
  OPENBLAS_NUM_THREADS=1 uv run python3 infra/immigration-fiscal/legacy_comparators_2026_09_30/group_lines.py

--case oct05 writes derived/group_lines_oct05.csv from the library's oct05 run (the v5 case adopted 2026-10-05): both
union rows carry the 3,039,720 added people at the case lane's amounts on every line (the engine union's lines are the
case's own), A1 and the all-residents slice are on the lineage's 42,752,213, and the gate reads the white lane's
rekey_summary_oct05.csv. The capital return is in each group's cost_bn row, as for sept29.

--case oct07 writes derived/group_lines_oct07.csv from the library's oct07 run (main case v6, main_case_2026_10_07: v5
plus the items of its payload's meta.items): as oct05, with the items' union parts on both union rows (the engine union's
lines are the case's own; the rough union takes the union-only lines and the user-fee item's carrier receipt lines at
the engine's amounts, the library's rule 5), every group's accrual on the 2026 separate-funds path, and the gate on the
white lane's rekey_summary_oct07.csv.

On oct05 and oct07 the library keys Pell by each group's IPEDS share and public higher education by its measured use
(the lead's decision of 2026-10-07, a named defect fix; sept29 keeps the September 27 keys), so the rough union's and
A1's other_federal_benefits and education_services rows carry those terms. On oct07 the library adds item 4's tuition
term on education_services; its hospital term stays beside the central (the team lead, 2026-10-07), so no
health_services row carries it.

On oct05 and oct07 the library's central keys every group's income taxes on the case's own keys (round 2, the team
lead's instruction of 2026-10-07): federal income tax on v4 item 3's IRS-raked key, state and other personal taxes on
the state-liability key, the shared allocation. The rough union's and A1's federal_income_tax, state_local_income_tax
and other_personal_tax rows carry those keys; sept29 keeps the CPS-dollar rule.

The live default, oct16, reads the completed white library's found v9 personal ends and writes only oct16 files.
The annual group costs include selected neutral items on each group's keys and canonical Mexican calibration/
coverage post terms. service_parts_oct16.json preserves pre-rule raw service amounts and typed own-group changes
for employee-pension attribution. R7 job-capital rules and inherited R9 pension rules remain. Earlier keyed
outputs remain archived and are not regenerated by the live run. Historical financing is a separate gated route.
"""
from __future__ import annotations

import csv
import importlib.util
import hashlib
import json
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
FISCAL = HERE.parent
WHITE = FISCAL / "white_replacement_2026_09_28"
_contract_spec = importlib.util.spec_from_file_location("legacy_line_comparison_contract", WHITE / "comparison_contract.py")
COMPARISON = importlib.util.module_from_spec(_contract_spec)
_contract_spec.loader.exec_module(COMPARISON)
_mortality_spec = importlib.util.spec_from_file_location("legacy_line_mortality", WHITE / "mortality_conventions.py")
MORTALITY = importlib.util.module_from_spec(_mortality_spec)
_mortality_spec.loader.exec_module(MORTALITY)
GROUPS = ("mexican_origin_engine", "mexican_origin_rough", "A1_third_plus_nh_white", "all_residents_slice")
BASES = ("cash", "accrual")
ENDS = ("low", "high")
SIDE = {"receipts": "receipt", "spending": "spending"}     # the debt lane's side names


def annual_mortality_label(rows):
    """This base route consumes general-mortality ratios; inherit its actual label."""
    labels = {r.get("mortality_convention") for r in rows}
    if labels != {MORTALITY.GENERAL}:
        raise SystemExit("[BLOCKED] base annual group lines lack the authoritative whole-population mortality label")
    return next(iter(labels))


def mixed_source_for_case(case):
    source = COMPARISON.load_mixed_unit(case=case)
    if source.get("comparison_case") != case:
        raise SystemExit("[BLOCKED] annual legacy mixed-unit source has the wrong case frame")
    return source


def load_rekey():
    spec = importlib.util.spec_from_file_location("rekey_sept29", WHITE / "rekey_sept29.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["rekey_sept29"] = module
    spec.loader.exec_module(module)
    return module


def main(case: str = "oct16") -> None:
    K = load_rekey()
    K.use_case(case)
    K.setup()
    K.stop_if_failed()
    scen = K.scenarios()
    summary = pd.read_csv(WHITE / f"derived/rekey_summary_{case}.csv")
    mortality = annual_mortality_label(summary.to_dict("records")) if case in ("oct15", "oct16") else None
    rows, fails, runs, service_runs = [], [], {}, []
    for basis in BASES:
        for end in ENDS:
            for g in GROUPS:
                run = K.run29(scen[g], end, basis)
                r, lines, _, _, _ = run
                runs[basis, end, g] = run
                if case == "oct16":
                    if "v9_service_parts" not in r or "v9_raw_service_lines" not in r:
                        raise SystemExit("[BLOCKED] oct16 pension export lacks explicit raw service lines and typed item parts")
                    service_runs.append(dict(group=g, basis=basis, end=end,
                        raw_lines=r["v9_raw_service_lines"], parts=r["v9_service_parts"]))
                want = summary[(summary.basis == basis) & (summary.group == g) & (summary.end == end)].iloc[0]
                control_cost = want.cost_evaluator_bn if case in ('oct15', 'oct16') else want.cost
                if abs(r["cost"] - control_cost) > 5e-5 or int(round(r["population"])) != int(want.population):
                    fails.append(f"{g} {basis} {end}: cost {r['cost']:.6f} vs {want.cost:.4f}")
                e = (K.FULL or K.DUMP)[basis][end]     # oct05: the case's dump (K.DUMP is its identified union)
                prod = next(x for x in e["lines"] if x["side"] == "scalar" and x["id"] == "production_gain_bn")
                for side, lid, national, amount, response in lines:
                    rows.append(dict(group=g, basis=basis, end=end, spec=e["spec"], side=SIDE[side], line=lid,
                                     national_bn=f"{national:.10f}", amount_bn=f"{amount:.10f}",
                                     response=f"{response:.10f}"))
                rows.append(dict(group=g, basis=basis, end=end, spec=e["spec"], side="scalar", line="cost_bn",
                                 national_bn="", amount_bn=f"{r['cost']:.10f}", response=""))
                rows.append(dict(group=g, basis=basis, end=end, spec=e["spec"], side="scalar", line="population",
                                 national_bn="", amount_bn=f"{r['population']:.4f}", response=""))
                rows.append(dict(group=g, basis=basis, end=end, spec=e["spec"], side="scalar",
                                 line="production_gain_bn", national_bn="",
                                 amount_bn=f"{(r['production_gain']):.10f}", response=""))
                print(f"  {basis:7s} {end:4s} {g:24s} cost {r['cost']:9.4f} (rekey_summary {want.cost:9.4f})"
                      f"  production {r['production_gain']:.4f} (dump {prod['effect_bn']:.4f})")
    if fails:
        raise SystemExit(f"[BLOCKED] group lines do not reproduce rekey_summary_{case}.csv: " + "; ".join(fails))
    if case == "oct16":
        case_summary = json.loads((FISCAL / "main_case_2026_10_16/derived/summary.json").read_text())["v9"]
        for basis, field in (("accrual", "band_bn"), ("cash", "cash_set_bn")):
            for index, end in enumerate(ENDS):
                actual = runs[basis, end, "mexican_origin_engine"][0]["cost"]
                target = case_summary[field][index]
                if abs(actual-target) > 1e-9:
                    raise SystemExit(f"[BLOCKED] oct16 annual export/case {basis}/{end} differs (1e-9bn)")
    if case in ("oct15", "oct16"):
        mixed = mixed_source_for_case(case)
        for row in rows:
            row.update(case=case, mortality_convention=mortality, engine=COMPARISON.engine_for(row["group"]))
        bridges, comparisons = [], []
        for basis in BASES:
            for end in ENDS:
                for part in COMPARISON.bridge_parts(runs[basis, end, "mexican_origin_engine"],
                    runs[basis, end, "mexican_origin_rough"], K.META.get("union_completion", {}).get("carriers", {})):
                    bridges.append(dict(case=case, basis=basis, end=end, row_type="bridge", lineage_engine="case",
                        comparator_engine="rough", mortality_convention=mortality, **part))
                lineage = runs[basis, end, "mexican_origin_rough"][0]
                item11 = K.META["mixed_unit_removal"]["by_end"][end]["total_bn"]
                for comparator in ("A1_third_plus_nh_white", "all_residents_slice"):
                    left, right = COMPARISON.engine_for("mexican_origin_rough"), COMPARISON.engine_for(comparator)
                    COMPARISON.require_same_engine({"engine": left}, {"engine": right})
                    other = runs[basis, end, comparator][0]
                    if abs(lineage["population"] - other["population"]) > 1e-6:
                        raise SystemExit("[BLOCKED] live annual legacy comparison has unequal populations (1e-6 persons)")
                    gap = lineage["cost"] - other["cost"]
                    removal = COMPARISON.comparator_removal(mixed, comparator, basis, end, other['population'])
                    comparisons.append(dict(case=case, basis=basis, end=end, row_type="comparison",
                        lineage="mexican_origin_rough", comparator=comparator, lineage_engine=left, comparator_engine=right,
                        mortality_convention=mortality, annual_removal_cost_gap_bn=gap-removal['bn'],
                        annual_one_sided_gap_bn=gap, comparator_cost_bn=other['cost']+removal['bn'],
                        comparator_item11_bn=removal['bn'], item11_paired_se_bn=removal['paired_se_bn'],
                        lineage_population=lineage["population"], comparator_population=other["population"],
                        annual_gap_without_item11_bn=gap-item11, lineage_item11_bn=item11,
                        mixed_unit_asymmetry=removal['scope'], framing=COMPARISON.MIXED_FRAME))
    out = HERE / "derived"
    out.mkdir(exist_ok=True)
    with open(out / f"group_lines_{case}.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    if case in ("oct15", "oct16"):
        with (out / f"case_rough_line_bridge_{case}.csv").open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(bridges[0]), lineterminator="\n")
            writer.writeheader()
            writer.writerows(bridges)
        with (out / f"annual_comparison_{case}.csv").open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(comparisons[0]), lineterminator="\n")
            writer.writeheader()
            writer.writerows(comparisons)
    if case == "oct16":
        dependencies = [WHITE / "rekey_sept29.py", WHITE / "v9_items.py",
                        FISCAL / "main_case_2026_10_16/derived/corrections.json",
                        FISCAL / "main_case_2026_10_16/derived/corrections_cash.json",
                        out / "group_lines_oct16.csv"]
        (out / "service_parts_oct16.json").write_text(json.dumps(dict(case=case, runs=service_runs,
            source_sha256={str(p.relative_to(FISCAL)): hashlib.sha256(p.read_bytes()).hexdigest()
                           for p in dependencies}), indent=2) + "\n")
    print(f"[written] derived/group_lines_{case}.csv: {len(rows)} rows")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--case", default="oct16", choices=["sept29", "oct05", "oct07", "oct14", "oct15", "oct16"],
                    help="oct16 (default, v9); earlier keyed cases are archived")
    main(ap.parse_args().case)
    sys.path.insert(0, str(FISCAL / "scripts"))
    from memory_budget import require_within_budget
    print(f"[memory] peak physical footprint {require_within_budget('Legacy group line export') / 1e9:.3f} GB")
