"""Replace everything after the appendix marker in RESULT.md with derived/spec_tables.md.

Run after render_tables.py:
  uv run --no-project python3 infra/immigration-fiscal/vending_restaurants_2026_09_24/assemble_result.py
"""
from lib import DERIVED, HERE

MARKER = "## Appendix: every computed specification"


def main() -> None:
    res = HERE / "RESULT.md"
    text = res.read_text()
    if MARKER not in text:
        raise SystemExit(f"[FAILED] marker '{MARKER}' not in RESULT.md")
    head = text[: text.index(MARKER) + len(MARKER)]
    res.write_text(head + "\n\nGenerated by `render_tables.py` from `derived/`; do not edit by hand.\n\n"
                   + (DERIVED / "spec_tables.md").read_text())
    print("RESULT.md appendix refreshed")


if __name__ == "__main__":
    main()
