def sha256(path):
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def inspect_zip(path):
    members = []
    with zipfile.ZipFile(path) as archive:
        bad = archive.testzip()
        if bad is not None:
            raise ValueError(f"CRC failure: {path.name}: {bad}")
        for item in archive.infolist():
            name = PurePosixPath(item.filename)
            if name.is_absolute() or ".." in name.parts or "\\" in item.filename:
                raise ValueError(f"Unsafe archive member: {item.filename}")
            if item.is_dir():
                continue
            digest = hashlib.sha256(archive.read(item)).hexdigest()
            members.append({"name": item.filename, "bytes": item.file_size,
                            "sha256": digest})
    return members


def stage(source):
    raw = ROOT / "raw"
    raw.mkdir(exist_ok=True)
    seen = {}
    rows = []
    for name in FILES:
        original = source / name
        digest = sha256(original)
        duplicate = seen.get(digest)
        canonical = duplicate or name
        staged = raw / canonical
        if staged.exists():
            if sha256(staged) != digest:
                raise ValueError(f"Existing staged file differs: {staged}")
        else:
            shutil.copy2(original, staged)
            if sha256(staged) != digest:
                raise ValueError(f"Copy verification failed: {staged}")
        seen.setdefault(digest, name)
        members = inspect_zip(staged) if name.endswith(".zip") else []
        rows.append({"input": str(original), "bytes": original.stat().st_size,
                     "sha256": digest, "staged": str(staged.relative_to(ROOT)),
                     "exact_duplicate_of": duplicate, "members": members})
    report = {"acquired": "2026-09-17", "source": "Operator-supplied local downloads",
              "files": rows}
    (ROOT / "manifest.json").write_text(json.dumps(report, indent=2) + "\n")
    lines = ["# Acquisition ledger", "", "Originals preserved; ZIP CRC and copied SHA-256 verified.",
             "Archives are locally staged, with byte-identical inputs sharing a canonical copy.", ""]
    baseline_record = ROOT / 'derived/nlsy/baseline_provenance.json'
    if baseline_record.exists():
        baseline = json.loads(baseline_record.read_text())
        if sha256(Path(baseline['source'])) != baseline['sha256']:
            raise ValueError('Existing NLS baseline changed since extraction')
        lines.append(f"Existing source reused, not a new supplied download: `{baseline['source']}` | "
                     f"{baseline['bytes']} bytes | sha256:{baseline['sha256']}. "
                     "Selected98 public fields are regenerated by `nlsy/extract.py`; "
                     "full provenance is in `derived/nlsy/baseline_provenance.json`. "
                     "This older release is not asserted to be the latest2026 release.")
    for row in rows:
        lines.append(f"2026-09-17 | `{Path(row['input']).name}` | `{row['input']}` | "
                     f"{row['bytes']} bytes | sha256:{row['sha256']} | `{row['staged']}`")
        if row["exact_duplicate_of"]:
            lines.append(f"Duplicate of `{row['exact_duplicate_of']}`; original retained.")
    (ROOT / "ACQUIRED.md").write_text("\n\n".join(lines) + "\n")
    for row in rows:
        print(f"{Path(row['input']).name}: {row['bytes']:,} bytes; "
              f"duplicate={row['exact_duplicate_of']}; {len(row['members'])} members")
        for member in row["members"]:
            if not member["name"].startswith("__MACOSX/"):
                print(f"  {member['name']} ({member['bytes']:,})")


